// Two steps. First the plan view: its script is bundled and inlined into one HTML file,
// written out as a TypeScript module the server imports. Then the server and all its
// dependencies go into one file, so Claude Desktop, the Claude Code plugin, Gemini CLI
// and `npx` can run it with nothing but Node installed.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

export const VIEW_MODULE = 'src/view/plan-view.generated.ts';

/** @type {import('esbuild').BuildOptions} */
export const viewOptions = {
  entryPoints: ['src/view/main.ts'],
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
};

/** The view as one self-contained HTML string, and the module that carries it. */
export async function viewModule() {
  const out = await build(viewOptions);
  const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const html = readFileSync('src/view/plan.html', 'utf8').replace('<!--SCRIPT-->', () => `<script>${js}</script>`);
  return `// Generated by scripts/build.mjs from src/view/. Do not edit by hand.\nexport const PLAN_VIEW_HTML = ${JSON.stringify(html)};\n`;
}

/** @type {import('esbuild').BuildOptions} */
export const options = {
  entryPoints: ['src/cli.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  legalComments: 'none',
  minify: true,
  banner: {
    js: "#!/usr/bin/env node\nimport { createRequire as __createRequire } from 'node:module';\nconst require = __createRequire(import.meta.url);",
  },
  outfile: 'dist/staffing-math.mjs',
  logLevel: 'warning',
};

/** The same server as one fetch handler, for Vercel. vercel.json routes every path to it. */
/** @type {import('esbuild').BuildOptions} */
export const vercelOptions = {
  ...options,
  entryPoints: ['src/vercel.ts'],
  outfile: 'api/index.mjs',
  banner: { js: "import { createRequire as __createRequire } from 'node:module';\nconst require = __createRequire(import.meta.url);" },
};

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  writeFileSync(VIEW_MODULE, await viewModule());
  await build(options);
  await build(vercelOptions);
}
